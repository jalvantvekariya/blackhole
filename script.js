let clock = new THREE.Clock();

function animate() {
  requestAnimationFrame(animate);

  const delta = clock.getDelta() * state.simSpeed;
  const time = clock.getElapsedTime();

  // 1. Update Black Hole Physical Scales
  const rsMeters = calculateSchwarzschildRadius(state.mass);
  const visualRadius = Math.max(0.6, Math.log10(state.mass) * 0.8 + 0.6); // Scaled for visibility
  
  eventHorizonMesh.scale.setScalar(visualRadius);
  photonRingMesh.scale.setScalar(visualRadius * 1.35);

  // Ergosphere scale & visibility
  if (state.ergosphereEnabled && state.spin > 0.05) {
    ergosphereMesh.visible = true;
    const ergoX = visualRadius * (1 + Math.sqrt(1 - state.spin * state.spin * 0.5));
    ergosphereMesh.scale.set(ergoX * 1.2, visualRadius * 1.05, ergoX * 1.2);
    ergosphereMesh.rotation.y += delta * state.spin * 2.0;
  } else {
    ergosphereMesh.visible = false;
  }

  // 2. Animate Accretion Disk Particles with Relativistic Doppler Boosting
  const posAttr = particleSystem.geometry.attributes.position;
  const colAttr = particleSystem.geometry.attributes.color;
  const mode = FILTER_MODES[state.activeFilter];

  // Camera direction for Doppler effect calculation
  const camDir = camera.position.clone().normalize();

  for (let i = 0; i < PARTICLE_COUNT; i++) {
    const p = particleData[i];

    // Keplerian orbital rotation speed modulated by Spin & Mass
    const omega = (p.speed * (1 + state.spin * 0.4)) / Math.max(visualRadius, 0.5);
    p.angle += omega * delta;

    // Inward spiral motion
    p.radius -= delta * 0.08 * state.accretionRate;
    if (p.radius < visualRadius * 1.1) {
      p.radius = 12.0; // Reset to outer rim when falling crossing horizon
    }

    const currentR = p.radius;
    const x = currentR * Math.cos(p.angle);
    const z = currentR * Math.sin(p.angle);
    const y = p.y + Math.sin(time * 2 + p.angle * 3) * p.turbulence;

    posAttr.setXYZ(i, x, y, z);

    // Relativistic Doppler Boosting Asymmetry (Approaching vs Receding side)
    const velVec = new THREE.Vector3(-Math.sin(p.angle), 0, Math.cos(p.angle));
    const dopplerDot = velVec.dot(camDir);
    const dopplerFactor = 1.0 + dopplerDot * 0.45 * (visualRadius / currentR);

    // Color Interpolation based on active Filter mode
    const normR = (currentR - visualRadius) / (12.0 - visualRadius);
    const clampedR = Math.max(0, Math.min(1, normR));

    let rCol = THREE.MathUtils.lerp(mode.innerColor[0], mode.outerColor[0], clampedR) * dopplerFactor;
    let gCol = THREE.MathUtils.lerp(mode.innerColor[1], mode.outerColor[1], clampedR) * dopplerFactor;
    let bCol = THREE.MathUtils.lerp(mode.innerColor[2], mode.outerColor[2], clampedR) * dopplerFactor;

    colAttr.setXYZ(i, Math.min(1, rCol), Math.min(1, gCol), Math.min(1, bCol));
  }

  posAttr.needsUpdate = true;
  colAttr.needsUpdate = true;

  // 3. Animate Relativistic Jets
  if (state.jetsEnabled && state.accretionRate > 0.02) {
    jetSystem.visible = true;
    const jPos = jetSystem.geometry.attributes.position;
    for (let i = 0; i < JET_PARTICLE_COUNT; i++) {
      let y = jPos.getY(i);
      const dir = y >= 0 ? 1 : -1;
      y += dir * delta * (12 + state.spin * 8);

      if (Math.abs(y) > 20) {
        y = dir * (0.2 + Math.random() * 0.5);
      }
      jPos.setY(i, y);
    }
    jetSystem.geometry.attributes.position.needsUpdate = true;
    jetSystem.rotation.y += delta * 0.5;
  } else {
    jetSystem.visible = false;
  }

  // 4. Mode-specific Mesh Visibility
  spacetimeGrid.visible = (state.activeFilter === 'SPACETIME');
  magneticLinesGroup.visible = (state.activeFilter === 'MAGNETIC');

  if (spacetimeGrid.visible) {
    spacetimeGrid.rotation.z += delta * 0.05;
  }
  if (magneticLinesGroup.visible) {
    magneticLinesGroup.rotation.y += delta * (0.2 + state.spin * 0.5);
  }

  // 5. Dynamic Gravitational Lensing Shader Uniform Update
  if (lensingDiskMesh) {
    lensingDiskMesh.material.uniforms.uTime.value = time;
    lensingDiskMesh.material.uniforms.uColorInner.value.setRGB(...mode.innerColor);
    lensingDiskMesh.material.uniforms.uColorOuter.value.setRGB(...mode.outerColor);
    // Orient lensing disk to face camera slightly
    lensingDiskMesh.lookAt(camera.position);
  }

  // 6. Update Controls and Render Scene
  controls.update();
  renderer.render(scene, camera);

  // 7. Update Real-time Telemetry Readouts
  updateTelemetryHUD(rsMeters);
}

// Update HUD Numerical Values
function updateTelemetryHUD(rsMeters) {
  const iscoMeters = calculateISCO(state.mass, state.spin);
  const tempK = calculateTemperature(state.mass, iscoMeters, state.accretionRate);
  const density = calculateDensity(iscoMeters, state.accretionRate, state.mass);
  const pressure = calculatePressure(density, tempK);
  const grav = calculateGravity(state.mass, iscoMeters);
  const velMs = calculateOrbitalVelocity(state.mass, iscoMeters);
  const velFracC = (velMs / C).toFixed(2);

  document.getElementById('hud-rs').innerText = `${(rsMeters / 1000).toFixed(2)} km`;
  document.getElementById('hud-isco').innerText = `${(iscoMeters / 1000).toFixed(2)} km`;
  document.getElementById('hud-temp').innerText = `${formatSci(tempK)} K`;
  document.getElementById('hud-pressure').innerText = `${formatSci(pressure)} Pa`;
  document.getElementById('hud-density').innerText = `${formatSci(density)} kg/m³`;
  document.getElementById('hud-gravity').innerText = `${formatSci(grav)} m/s²`;
  document.getElementById('hud-velocity').innerText = `${velFracC}c`;

  // Time Dilation
  document.getElementById('td-outer').innerText = `${calculateTimeDilation(state.mass, rsMeters * 5).toFixed(2)}x`;
  document.getElementById('td-inner').innerText = `${calculateTimeDilation(state.mass, rsMeters * 2).toFixed(2)}x`;
  document.getElementById('td-horizon').innerText = `${calculateTimeDilation(state.mass, rsMeters * 1.01).toFixed(2)}x`;
}

