// Gravitational Lensing Secondary Warp Halo (Warped Disk Visual)
function createGravitationalLensingMesh() {
  const geo = new THREE.RingGeometry(1.2, 5.5, 96, 16);
  // Custom Vertex Warping Shader to simulate Einstein Light Bending over Horizon
  const mat = new THREE.ShaderMaterial({
    uniforms: {
      uTime: { value: 0 },
      uColorInner: { value: new THREE.Color(1.0, 0.9, 0.7) },
      uColorOuter: { value: new THREE.Color(0.9, 0.3, 0.05) },
      uOpacity: { value: 0.6 }
    },
    vertexShader: `
      varying vec2 vUv;
      varying float vDist;
      void main() {
        vUv = uv;
        vec3 pos = position;
        float r = length(pos.xy);
        // Vertical warp simulation for gravitational lensing arc
        pos.z += sin(r * 2.0) * 0.15 * (1.0 / (r - 0.9));
        vDist = r;
        gl_Position = projectionMatrix * modelViewMatrix * vec4(pos, 1.0);
      }
    `,
    fragmentShader: `
      uniform vec3 uColorInner;
      uniform vec3 uColorOuter;
      uniform float uOpacity;
      varying float vDist;
      void main() {
        float t = smoothstep(1.2, 5.5, vDist);
        vec3 col = mix(uColorInner, uColorOuter, t);
        float alpha = (1.0 - t) * uOpacity * smoothstep(1.2, 1.5, vDist);
        gl_FragColor = vec4(col, alpha);
      }
    `,
    transparent: true,
    side: THREE.DoubleSide,
    blending: THREE.AdditiveBlending,
    depthWrite: false
  });

  lensingDiskMesh = new THREE.Mesh(geo, mat);
  lensingDiskMesh.rotation.x = Math.PI / 2.3; // Angle offset for lensing effect
  scene.add(lensingDiskMesh);
}

// Primary Accretion Disk (16,000 Particle Swarm)
function createAccretionDisk() {
  const geo = new THREE.BufferGeometry();
  particlePositions = new Float32Array(PARTICLE_COUNT * 3);
  particleColors = new Float32Array(PARTICLE_COUNT * 3);
  particleData = [];

  const innerR = 2.2;
  const outerR = 12.0;

  for (let i = 0; i < PARTICLE_COUNT; i++) {
    const r = innerR + Math.pow(Math.random(), 2.2) * (outerR - innerR);
    const theta = Math.random() * Math.PI * 2;
    const yHeight = (Math.random() - 0.5) * 0.18 * (r / outerR); // Thin disk profile

    particlePositions[i * 3] = r * Math.cos(theta);
    particlePositions[i * 3 + 1] = yHeight;
    particlePositions[i * 3 + 2] = r * Math.sin(theta);

    particleColors[i * 3] = 1.0;
    particleColors[i * 3 + 1] = 0.5;
    particleColors[i * 3 + 2] = 0.2;

    particleData.push({
      radius: r,
      angle: theta,
      y: yHeight,
      speed: 0.8 / Math.sqrt(r), // Keplerian velocity curve
      turbulence: (Math.random() - 0.5) * 0.02
    });
  }

  geo.setAttribute('position', new THREE.BufferAttribute(particlePositions, 3));
  geo.setAttribute('color', new THREE.BufferAttribute(particleColors, 3));

  const mat = new THREE.PointsMaterial({
    size: 0.12,
    vertexColors: true,
    transparent: true,
    opacity: 0.85,
    blending: THREE.AdditiveBlending,
    depthWrite: false
  });

  particleSystem = new THREE.Points(geo, mat);
  scene.add(particleSystem);
}

// Relativistic Jets
function createJets() {
  const geo = new THREE.BufferGeometry();
  jetPositions = new Float32Array(JET_PARTICLE_COUNT * 3);
  jetColors = new Float32Array(JET_PARTICLE_COUNT * 3);

  for (let i = 0; i < JET_PARTICLE_COUNT; i++) {
    const dir = Math.random() > 0.5 ? 1 : -1;
    const h = Math.random() * 18;
    const r = (Math.random() * 0.1 + 0.02) * (1 + h * 0.2);
    const theta = Math.random() * Math.PI * 2;

    jetPositions[i * 3] = r * Math.cos(theta);
    jetPositions[i * 3 + 1] = h * dir;
    jetPositions[i * 3 + 2] = r * Math.sin(theta);

    jetColors[i * 3] = 0.3;
    jetColors[i * 3 + 1] = 0.7;
    jetColors[i * 3 + 2] = 1.0;
  }

  geo.setAttribute('position', new THREE.BufferAttribute(jetPositions, 3));
  geo.setAttribute('color', new THREE.BufferAttribute(jetColors, 3));

  const mat = new THREE.PointsMaterial({
    size: 0.16,
    vertexColors: true,
    transparent: true,
    opacity: 0.7,
    blending: THREE.AdditiveBlending,
    depthWrite: false
  });

  jetSystem = new THREE.Points(geo, mat);
  scene.add(jetSystem);
}

