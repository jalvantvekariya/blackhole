function setupUI() {
  // Sliders Binding
  bindSlider('input-mass', 'val-mass', ' M☉', (v) => { state.mass = parseFloat(v); });
  bindSlider('input-spin', 'val-spin', '', (v) => { state.spin = parseFloat(v); });
  bindSlider('input-accretion', 'val-accretion', '', (v) => { state.accretionRate = parseFloat(v); });
  bindSlider('input-angle', 'val-angle', '°', (v) => {
    state.viewingAngle = parseFloat(v);
    setCameraAngle(state.viewingAngle);
  });
  bindSlider('input-speed', 'val-speed', 'x', (v) => { state.simSpeed = parseFloat(v); });

  // Toggles Binding
  document.getElementById('toggle-jets').addEventListener('change', (e) => {
    state.jetsEnabled = e.target.checked;
  });
  document.getElementById('toggle-ergosphere').addEventListener('change', (e) => {
    state.ergosphereEnabled = e.target.checked;
  });

  // Black Hole Type Selector
  document.getElementById('select-type').addEventListener('change', (e) => {
    const type = e.target.value;
    if (type === 'stellar') updateMassSlider(10.0);
    else if (type === 'intermediate') updateMassSlider(1000.0);
    else if (type === 'supermassive') updateMassSlider(1000000.0);
  });

  // Presets Selector
  document.getElementById('select-preset').addEventListener('change', (e) => {
    applyPreset(e.target.value);
  });

  // Camera Presets Buttons
  document.querySelectorAll('.btn-preset-cam').forEach(btn => {
    btn.addEventListener('click', () => {
      const mode = btn.getAttribute('data-cam');
      triggerCameraPreset(mode);
    });
  });

  // Filter Bar Buttons
  document.querySelectorAll('.btn-filter').forEach(btn => {
    btn.addEventListener('click', () => {
      setFilterMode(btn.getAttribute('data-filter'));
    });
  });

  // Panel Collapsing
  document.getElementById('toggle-controls').addEventListener('click', () => {
    document.getElementById('panel-controls').classList.toggle('collapsed');
  });
  document.getElementById('toggle-hud').addEventListener('click', () => {
    document.getElementById('panel-hud').classList.toggle('collapsed');
  });

  // Modal Dialogs
  const modal = document.getElementById('modal-about');
  document.getElementById('btn-about').addEventListener('click', () => modal.classList.remove('hidden'));
  document.getElementById('modal-close').addEventListener('click', () => modal.classList.add('hidden'));

  // Reset Button
  document.getElementById('btn-reset').addEventListener('click', resetSimulation);

  // Keyboard Shortcuts
  window.addEventListener('keydown', (e) => {
    if (e.key >= '0' && e.key <= '9') {
      const filterKeys = ['TIMEDILATION', 'NORMAL', 'XRAY', 'TEMPERATURE', 'PRESSURE', 'DENSITY', 'GRAVITY', 'VELOCITY', 'SPACETIME', 'MAGNETIC'];
      setFilterMode(filterKeys[parseInt(e.key)]);
    } else if (e.key.toLowerCase() === 'r') {
      resetSimulation();
    } else if (e.key.toLowerCase() === 'g') {
      triggerCameraPreset('gods');
    } else if (e.key.toLowerCase() === 'j') {
      const toggle = document.getElementById('toggle-jets');
      toggle.checked = !toggle.checked;
      state.jetsEnabled = toggle.checked;
    } else if (e.key.toLowerCase() === 'e') {
      const toggle = document.getElementById('toggle-ergosphere');
      toggle.checked = !toggle.checked;
      state.ergosphereEnabled = toggle.checked;
    }
  });
}

function bindSlider(id, readoutId, suffix, callback) {
  const input = document.getElementById(id);
  const readout = document.getElementById(readoutId);
  input.addEventListener('input', (e) => {
    const val = e.target.value;
    readout.innerText = val + suffix;
    callback(val);
  });
}

function updateMassSlider(val) {
  state.mass = val;
  const slider = document.getElementById('input-mass');
  slider.max = Math.max(100, val).toString();
  slider.value = val;
  document.getElementById('val-mass').innerText = `${val} M☉`;
}

function setFilterMode(modeKey) {
  if (!FILTER_MODES[modeKey]) return;
  state.activeFilter = modeKey;

  // UI Active Button Update
  document.querySelectorAll('.btn-filter').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-filter') === modeKey);
  });

  // HUD Info Box Update
  const modeInfo = FILTER_MODES[modeKey];
  document.getElementById('info-box-title').innerText = modeInfo.title;
  document.getElementById('info-box-desc').innerText = modeInfo.desc;
}

function setCameraAngle(degrees) {
  const rad = (degrees * Math.PI) / 180;
  const dist = camera.position.length();
  camera.position.x = 0;
  camera.position.y = dist * Math.cos(rad);
  camera.position.z = dist * Math.sin(rad);
  camera.lookAt(0, 0, 0);
}

function triggerCameraPreset(preset) {
  state.cameraPreset = preset;
  if (preset === 'orbit') {
    camera.position.set(0, 18, 38);
  } else if (preset === 'top') {
    camera.position.set(0, 45, 0.1);
  } else if (preset === 'side') {
    camera.position.set(45, 0, 0);
  } else if (preset === 'edge') {
    camera.position.set(0, 0.5, 42);
  } else if (preset === 'gods') {
    camera.position.set(22, 35, 22);
  }
  camera.lookAt(0, 0, 0);
}

function applyPreset(presetKey) {
  if (presetKey === 'quiet') {
    updateMassSlider(10);
    state.spin = 0.1;
    state.accretionRate = 0.05;
    state.jetsEnabled = false;
  } else if (presetKey === 'active') {
    updateMassSlider(20);
    state.spin = 0.85;
    state.accretionRate = 0.9;
    state.jetsEnabled = true;
  } else if (presetKey === 'spin') {
    updateMassSlider(15);
    state.spin = 0.998;
    state.accretionRate = 0.5;
    state.ergosphereEnabled = true;
  } else if (presetKey === 'extreme') {
    updateMassSlider(80);
    state.spin = 0.95;
    state.accretionRate = 1.0;
  } else if (presetKey === 'supermassive') {
    updateMassSlider(1000000);
    state.spin = 0.70;
    state.accretionRate = 0.4;
  } else if (presetKey === 'binary') {
    updateMassSlider(14);
    state.spin = 0.65;
    state.accretionRate = 0.8;
    setFilterMode('XRAY');
  } else if (presetKey === 'jet') {
    updateMassSlider(30);
    state.spin = 0.92;
    state.accretionRate = 0.85;
    state.jetsEnabled = true;
  } else if (presetKey === 'educational') {
    updateMassSlider(10);
    state.spin = 0.72;
    state.accretionRate = 0.35;
    setFilterMode('NORMAL');
  }

  // Update UI Inputs
  document.getElementById('input-spin').value = state.spin;
  document.getElementById('val-spin').innerText = state.spin.toFixed(3);
  document.getElementById('input-accretion').value = state.accretionRate;
  document.getElementById('val-accretion').innerText = state.accretionRate.toFixed(2);
  document.getElementById('toggle-jets').checked = state.jetsEnabled;
  document.getElementById('toggle-ergosphere').checked = state.ergosphereEnabled;
}

function resetSimulation() {
  state.mass = 10.0;
  state.spin = 0.720;
  state.accretionRate = 0.35;
  state.viewingAngle = 65;
  state.simSpeed = 1.0;
  state.jetsEnabled = true;
  state.ergosphereEnabled = false;

  updateMassSlider(10.0);
  document.getElementById('input-spin').value = 0.720;
  document.getElementById('val-spin').innerText = '0.720';
  document.getElementById('input-accretion').value = 0.35;
  document.getElementById('val-accretion').innerText = '0.35';
  document.getElementById('input-angle').value = 65;
  document.getElementById('val-angle').innerText = '65°';
  document.getElementById('input-speed').value = 1.0;
  document.getElementById('val-speed').innerText = '1.0x';
  document.getElementById('toggle-jets').checked = true;
  document.getElementById('toggle-ergosphere').checked = false;
  document.getElementById('select-preset').value = 'default';
  document.getElementById('select-type').value = 'stellar';

  setFilterMode('NORMAL');
  triggerCameraPreset('orbit');
}

