// Spacetime Curvature Coordinate Grid
function createSpacetimeGrid() {
  const size = 30;
  const divisions = 40;
  const geo = new THREE.PlaneGeometry(size, size, divisions, divisions);
  geo.rotateX(-Math.PI / 2);

  const pos = geo.attributes.position;
  for (let i = 0; i < pos.count; i++) {
    const x = pos.getX(i);
    const z = pos.getZ(i);
    const r = Math.sqrt(x * x + z * z);
    const warp = -2.5 / (r + 0.8); // Gravitational well deformation
    pos.setY(i, warp);
  }
  geo.computeVertexNormals();

  const mat = new THREE.MeshBasicMaterial({
    color: 0x8b5cf6,
    wireframe: true,
    transparent: true,
    opacity: 0.25
  });

  spacetimeGrid = new THREE.Mesh(geo, mat);
  spacetimeGrid.position.y = -2;
  spacetimeGrid.visible = false;
  scene.add(spacetimeGrid);
}

// Illustrative Magnetic Field Lines
function createMagneticFieldLines() {
  magneticLinesGroup = new THREE.Group();
  const lineCount = 16;

  for (let i = 0; i < lineCount; i++) {
    const angle = (i / lineCount) * Math.PI * 2;
    const curve = new THREE.CubicBezierCurve3(
      new THREE.Vector3(0, 0.2, 0),
      new THREE.Vector3(Math.cos(angle) * 6, 8, Math.sin(angle) * 6),
      new THREE.Vector3(Math.cos(angle) * 12, -8, Math.sin(angle) * 12),
      new THREE.Vector3(0, -0.2, 0)
    );

    const points = curve.getPoints(50);
    const geo = new THREE.BufferGeometry().setFromPoints(points);
    const mat = new THREE.LineBasicMaterial({
      color: 0xf59e0b,
      transparent: true,
      opacity: 0.4
    });

    const line = new THREE.Line(geo, mat);
    magneticLinesGroup.add(line);
  }

  magneticLinesGroup.visible = false;
  scene.add(magneticLinesGroup);
}

// Multi-layered Starfield
function createStarField() {
  const count = 3000;
  const geo = new THREE.BufferGeometry();
  const pos = new Float32Array(count * 3);
  const colors = new Float32Array(count * 3);

  for (let i = 0; i < count; i++) {
    const r = 150 + Math.random() * 200;
    const theta = Math.random() * Math.PI * 2;
    const phi = Math.acos((Math.random() * 2) - 1);

    pos[i * 3] = r * Math.sin(phi) * Math.cos(theta);
    pos[i * 3 + 1] = r * Math.sin(phi) * Math.sin(theta);
    pos[i * 3 + 2] = r * Math.cos(phi);

    const brightness = 0.4 + Math.random() * 0.6;
    colors[i * 3] = brightness;
    colors[i * 3 + 1] = brightness * (0.8 + Math.random() * 0.2);
    colors[i * 3 + 2] = brightness;
  }

  geo.setAttribute('position', new THREE.BufferAttribute(pos, 3));
  geo.setAttribute('color', new THREE.BufferAttribute(colors, 3));

  const mat = new THREE.PointsMaterial({
    size: 1.2,
    vertexColors: true,
    transparent: true,
    opacity: 0.8
  });

  starField = new THREE.Points(geo, mat);
  scene.add(starField);
}

