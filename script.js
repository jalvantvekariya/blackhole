// 3. PHYSICS COMPUTATION FUNCTIONS
// ==========================================================================
function calculateSchwarzschildRadius(massMsolar) {
  const mKg = massMsolar * SOLAR_MASS;
  return (2 * G * mKg) / (C * C); // meters
}

// Innermost Stable Circular Orbit (ISCO) Kerr approximation
function calculateISCO(massMsolar, spin) {
  const rs = calculateSchwarzschildRadius(massMsolar);
  const rh = rs / 2; // Approximate Kerr horizon
  // Z1, Z2 Kerr factors approximation
  const Z1 = 1 + Math.pow(1 - spin * spin, 1/3) * (Math.pow(1 + spin, 1/3) + Math.pow(1 - spin, 1/3));
  const Z2 = Math.sqrt(3 * spin * spin + Z1 * Z1);
  const rms = rh * (3 + Z2 - Math.sqrt((3 - Z1) * (3 + Z1 + 2 * Z2)));
  return Math.max(rms, rh * 1.1);
}

function calculateOrbitalVelocity(massMsolar, radiusMeters) {
  const mKg = massMsolar * SOLAR_MASS;
  const v = Math.sqrt((G * mKg) / radiusMeters);
  return Math.min(v, C * 0.999); // Physical clamp below c
}

function calculateTemperature(massMsolar, radiusMeters, accretionRate) {
  const rs = calculateSchwarzschildRadius(massMsolar);
  const ratio = Math.max(radiusMeters / rs, 1.2);
  // Standard Shakura-Sunyaev disk temperature profile T(r) ∝ r^(-3/4)
  const baseT = 1.2e7 * Math.pow(10 / massMsolar, 0.25) * Math.pow(accretionRate, 0.25);
  return baseT * Math.pow(ratio, -0.75);
}

function calculateDensity(radiusMeters, accretionRate, massMsolar) {
  const rs = calculateSchwarzschildRadius(massMsolar);
  const rNorm = Math.max(radiusMeters / rs, 1.0);
  return (2.4e-6 * accretionRate) / Math.pow(rNorm, 1.5); // kg/m^3
}

function calculatePressure(density, temperature) {
  const n = density / (1.67e-27); // Proton number density approx
  return n * BOLTZMANN * temperature; // Pa
}

function calculateGravity(massMsolar, radiusMeters) {
  const mKg = massMsolar * SOLAR_MASS;
  return (G * mKg) / (radiusMeters * radiusMeters); // m/s^2
}

function calculateTimeDilation(massMsolar, radiusMeters) {
  const rs = calculateSchwarzschildRadius(massMsolar);
  if (radiusMeters <= rs) return 0.0;
  return Math.sqrt(1.0 - (rs / radiusMeters));
}

// Format numbers nicely into scientific notation
function formatSci(val, decimals = 2) {
  if (val === 0) return "0";
  const exp = Math.floor(Math.log10(Math.abs(val)));
  const mantissa = val / Math.pow(10, exp);
  if (Math.abs(exp) < 3) return val.toFixed(decimals);
  return `${mantissa.toFixed(decimals)} × 10¹³`.replace('10¹³', `10${getSuperscript(exp)}`);
}

function getSuperscript(num) {
  const supers = {'-': '⁻', '0': '⁰', '1': '¹', '2': '²', '3': '³', '4': '⁴', '5': '⁵', '6': '⁶', '7': '⁷', '8': '⁸', '9': '⁹'};
  return String(num).split('').map(c => supers[c] || c).join('');
}

